/** Host and browser can render the same confirmed change in their own language. */
export function hostSuccessKey(application: HostEngineApplication, restoring: boolean) {
  switch (application) {
    case 'applied': return restoring ? 'hostRestoreApplied' : 'hostTakeoverApplied'
    case 'restart-required': return restoring ? 'hostRestorePending' : 'hostTakeoverPending'
    case 'unchanged': return restoring ? 'hostRestoreUnchanged' : 'hostTakeoverUnchanged'
    default: return undefined
  }
}

